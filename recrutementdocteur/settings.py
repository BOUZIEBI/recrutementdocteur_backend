def get_env_bool(
    variable_name: str,
    default: bool = False,
) -> bool:
    """
    Convertit une variable d'environnement en booléen Python.
    """

    value = os.getenv(variable_name)

    if value is None:
        return default

    return value.strip().lower() in {
        "true",
        "1",
        "yes",
        "on",
    }


